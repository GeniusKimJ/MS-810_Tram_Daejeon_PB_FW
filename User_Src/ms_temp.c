s16 TempAmbient(u16 adc) 
{
	static const u16 Th103AT[142U] = {	// -50 ~ 90 degree(15-bit extended data) after 250321
	   31522,    31463,  31400,    31335, 	 31268,	  31197,  31124,    31047, 30969,  30888,
	   30798,    30727,  30650,    30567,    30477,   30379,  30273,    30158, 30030,  29890,
	   29735,    29631,  29520,    29402,    29274,   29136,  28986,    28824, 28648,  28454,
	   28242,    28100,  27948,    27787,    27614,   27429,  27230,    27016, 26785,  26534,
	   26260,    26077,  25882,    25676,    25457,   25225,  24977,    24712, 24429,  24125,
	   23797,    23576,  23344,    23099,    22842,   22570,  22284,    21980, 21659,  21318,
	   20951,    20704,  20447,    20178,    19897,   19603,  19296,    18974, 18636,  18281,
	   17908,    17653,  17389,    17116,    16833,   16540,  16235,    15919, 15590,  15249,
	   14891,    14647,  14396,    14138,    13873,   13600,  13319,    13030, 12732,  12424,
	   12100,    11880,  11655,    11425,    11191,   10951,  10706,    10455, 10198,  9936,
	   9662,     9475,   9284,     9091,     8894,    8694,   8491,     8284,  8074,   7860,
	   7629,     7476,   7320,     7163,     7004,    6843,   6680,     6515,  6348,   6179,
	   5987,     5864,   5740,     5615,     5488,    5360,   5231,     5101,  4970,   4837,
	   4689,     4592,   4495,     4397,     4298,    4199,   4099,     3998,  3897,   3795,
	   3679,     3604
	};


	u8		quota = (sizeof(Th103AT)/sizeof(s16))/8U;
	s16		data, denom;
	u16     u16_buf;
	u16     u16_buf2;
	s16     s16_buf;
	//u8		uint8_buf;

	if(adc > Th103AT[quota*4U]) {
		if(adc > Th103AT[quota*2U])	{
			if(adc > (u16)Th103AT[quota]) {
				quota = 0U;
			}
			//else						quota = quota * 1U;
		} else {
			if(adc > Th103AT[quota*3U]) {
				quota = quota * 2U;
			} else {
				quota = quota * 3U;
			}
		}
	} else {
		if(adc > Th103AT[quota*6U]) {
			if(adc > Th103AT[quota*5U]) {
				quota = quota * 4U;
			} else {
				quota = quota * 5U;
			}
		} else {
			if(adc > Th103AT[quota*7U])	{
				quota = quota * 6U;
			} else {
				quota = quota * 7U;
			}
		}
	}

	for(; quota < (sizeof(Th103AT)/sizeof(s16)); quota++) {			// Scan 0 ~ 100?
		if(adc >= Th103AT[quota]) {
			break;
		}
	}

	if(quota > ((sizeof(Th103AT)/sizeof(s16))-1U)) {
		quota = (u8)((sizeof(Th103AT)/sizeof(s16))-1U); // quota Max 141
	}
	if(quota == 0U) {
		data = -500;		// Open or under -50.1 - kDk
	} else if(quota == 141U) {
		data = (s16)900L;
	} else {
		//data = (s16)((adc - Th103AT[quota]) * 10U);					// For rerolution 0.1?
		u16_buf = Th103AT[quota];
		u16_buf = (adc - u16_buf) * 10U;
		data = (s16)(u16_buf);

		//denom = Th103AT[quota-1] - Th103AT[quota];
		//uint8_buf = quota-1U;
		u16_buf = Th103AT[quota-1U];
		u16_buf2 = Th103AT[quota];
		u16_buf = u16_buf - u16_buf2;
		denom = (s16)(u16_buf);

		//data = (((quota * 10U) - (data / denom)) - 400U);					// 1? Table
		u16_buf = (u16)((u16)quota * 10U);
		s16_buf = (s16)(data / denom);
		u16_buf2 = (u16)s16_buf;
		u16_buf = (u16_buf - u16_buf2) - (u16)500U;
		data = (s16)(u16_buf);

		if(data > 1400L) {
			data = (s16)1400L;
		}
	}
	return	data;
}

